_NAMESPACE = uuid5(NAMESPACE_DNS, "pixel-lane.demo-district")

DEMO_DISTRICT_CITY_ID = uuid5(_NAMESPACE, "city")
DEMO_DISTRICT_CITY_NAME = "Demo District"
DEMO_DISTRICT_DESCRIPTION = (
    "Synthetic renderer-showcase district (Road + Lane Representation V2) -- "
    "not a real place. Generated deterministically by "
    "app.city.examples.demo_district.build_demo_district(); exercises the same "
    "City Model domain objects and rendering pipeline as a real OSM import. "
    "See docs/city-model.md's Demo City section for what this covers and "
    "what is intentionally out of scope."
)


def _id(*parts: object) -> UUID:
    return uuid5(_NAMESPACE, ":".join(str(p) for p in parts))


def _pt(x: float, y: float) -> Point:
    return Point(x=x, y=y)


class _RoadBuilder:
    """Small internal helper so each road below reads as data, not a wall
    of repeated `LaneCreate(id=..., ...)` boilerplate. Not exported --
    this file's only public surface is `build_demo_district()`."""

    def __init__(self) -> None:
        self.roads: list[RoadCreate] = []
        self.lane_ids_by_key: dict[tuple[str, int], UUID] = {}

    def add_road(
        self,
        name: str,
        *,
        key: str | None = None,
        road_type: RoadType,
        points: list[tuple[float, float]],
        lanes: list[dict],
        one_way: bool | None = None,
        median: MedianType = MedianType.NONE,
        speed_limit_kmh: float = 50.0,
    ) -> UUID:
        """`name` is the user-facing map label -- several segments of the
        same real-world street (e.g. a divided arterial's two
        carriageways, or a lane-drop's two sub-segments) intentionally
        share one `name` so they de-duplicate into a single label (see
        `cityModelToGeoJson.buildRoadLabelFeatureCollection`), instead of
        each segment's internal identity leaking into the map as its own
        debug-looking label. `key` is that internal identity (defaults to
        `name` when segments don't repeat it) -- unique per segment,
        used only for deterministic id generation and lane lookups.
        """
        road_key = key or name
        road_id = _id("road", road_key)
        lane_creates: list[LaneCreate] = []
        for lane in lanes:
            lane_id = _id("lane", road_key, lane["index"])
            self.lane_ids_by_key[(road_key, lane["index"])] = lane_id
            lane_creates.append(
                LaneCreate(
                    id=lane_id,
                    index=lane["index"],
                    direction=lane.get("direction", LaneDirection.FORWARD),
                    allowed_movements=lane.get("allowed_movements", [MovementType.STRAIGHT]),
                    lane_type=lane.get("lane_type", LaneType.GENERAL),
                    speed_limit_kmh=lane.get("speed_limit_kmh"),
                    allowed_turns=lane.get("allowed_turns"),
                )
            )
        self.roads.append(
            RoadCreate(
                id=road_id,
                name=name,
                road_type=road_type,
                geometry=Polyline(points=[_pt(x, y) for x, y in points]),
                default_speed_limit_kmh=speed_limit_kmh,
                one_way=one_way,
                median=median,
                carriageway_count=1,
                lanes=lane_creates,
            )
        )
        return road_id

    def lane_id(self, key: str, index: int) -> UUID:
        return self.lane_ids_by_key[(key, index)]


def build_demo_district() -> CityCreate:
    """Builds the Demo District as a validated `CityCreate` payload.

    Deterministic: calling this twice produces byte-identical ids, so
    re-seeding is idempotent (see `seed_demo_district.py`).
    """
    b = _RoadBuilder()

    # --- Turan Avenue: main divided arterial (6 lanes total across two
    # one-way carriageways, physical median, bus lane, turn pockets) ------
    # Both carriageways share the display name "Turan Avenue" -- they are
    # the same real-world street, and buildRoadLabelFeatureCollection
    # already de-duplicates by name, so this alone gives one clean label
    # instead of two "(eastbound)"/"(westbound)" debug-looking ones (see
    # docs/city-model.md's label-improvement note).
    eastbound = b.add_road(
        "Turan Avenue",
        key="turan-eastbound",
        road_type=RoadType.ARTERIAL,
        points=[(0.0, 152.0), (180.0, 152.0), (220.0, 152.0), (400.0, 152.0)],
        one_way=True,
        median=MedianType.PHYSICAL,
        speed_limit_kmh=60.0,
        lanes=[
            {"index": 0, "lane_type": LaneType.BUS},
            {"index": 1},
            {
                "index": 2,
                "lane_type": LaneType.TURN_ONLY,
                "allowed_movements": [MovementType.RIGHT],
                "allowed_turns": [TurnLaneType.RIGHT],
            },
        ],
    )
    westbound = b.add_road(
        "Turan Avenue",
        key="turan-westbound",
        road_type=RoadType.ARTERIAL,
        points=[(400.0, 148.0), (220.0, 148.0), (180.0, 148.0), (0.0, 148.0)],
        one_way=True,
        median=MedianType.PHYSICAL,
        speed_limit_kmh=60.0,
        lanes=[
            {
                "index": 0,
                "lane_type": LaneType.TURN_ONLY,
                "allowed_movements": [MovementType.LEFT],
                "allowed_turns": [TurnLaneType.LEFT],
            },
            {"index": 1},
            {
                "index": 2,
                "allowed_movements": [MovementType.STRAIGHT, MovementType.RIGHT],
                "allowed_turns": [TurnLaneType.THROUGH, TurnLaneType.RIGHT],
            },
        ],
    )

    # --- Zhastar Street: secondary arterial, undivided, 4 lanes total,
    # with a lane drop northbound and lane addition (same segment pair,
    # read in the other direction) ---------------------------------------
    zhastar_north_near = b.add_road(
        "Zhastar Street",
        key="zhastar-north-near",
        road_type=RoadType.ARTERIAL,
        points=[(200.0, 152.0), (200.0, 220.0)],
        one_way=True,
        speed_limit_kmh=50.0,
        lanes=[
            {
                "index": 0,
                "lane_type": LaneType.TURN_ONLY,
                "allowed_movements": [MovementType.LEFT],
                "allowed_turns": [TurnLaneType.LEFT],
            },
            {
                "index": 1,
                "allowed_movements": [MovementType.STRAIGHT, MovementType.RIGHT],
                "allowed_turns": [TurnLaneType.THROUGH, TurnLaneType.RIGHT],
            },
        ],
    )
    # Lane drop: only 1 lane continues past the pass-through node -- this
    # falls out naturally from two sequential Roads with different lane
    # counts (the same mechanism a real OSM import already produces when
    # `lanes` differs between segments, see client.py's edge_attrs_differ).
    zhastar_north_far = b.add_road(
        "Zhastar Street",
        key="zhastar-north-far",
        road_type=RoadType.ARTERIAL,
        points=[(200.0, 220.0), (200.0, 300.0)],
        one_way=True,
        speed_limit_kmh=50.0,
        lanes=[{"index": 0}],
    )
    zhastar_south = b.add_road(
        "Zhastar Street",
        key="zhastar-south",
        road_type=RoadType.ARTERIAL,
        points=[(200.0, 300.0), (200.0, 148.0)],
        one_way=True,
        speed_limit_kmh=50.0,
        lanes=[
            {"index": 0},
            {
                "index": 1,
                "lane_type": LaneType.TURN_ONLY,
                "allowed_movements": [MovementType.RIGHT],
                "allowed_turns": [TurnLaneType.RIGHT],
            },
        ],
    )

    # --- Samal Street: ordinary two-way local street with parking --------
    samal = b.add_road(
        "Samal Street",
        road_type=RoadType.RESIDENTIAL,
        points=[(320.0, 50.0), (320.0, 150.0), (320.0, 250.0)],
        one_way=False,
        speed_limit_kmh=30.0,
        lanes=[{"index": 0}],
    )

    # --- Bereke Lane: one-way local street --------------------------------
    bereke = b.add_road(
        "Bereke Lane",
        road_type=RoadType.RESIDENTIAL,
        points=[(80.0, 50.0), (80.0, 150.0), (80.0, 250.0)],
        one_way=True,
        speed_limit_kmh=30.0,
        lanes=[{"index": 0}],
    )

    # --- Cycle Path: dedicated bike lane, parallel to Bereke Lane ---------
    b.add_road(
        "Cycle Path",
        road_type=RoadType.SERVICE,
        points=[(60.0, 50.0), (60.0, 150.0), (60.0, 250.0)],
        one_way=True,
        speed_limit_kmh=20.0,
        lanes=[{"index": 0, "lane_type": LaneType.BICYCLE}],
    )

    # --- Kokzhiek Access Road: short one-way service/access spur ----------
    # Its start point exactly matches Samal Street's own last point --
    # this is a real graph connection (see the T-junction Intersection
    # below), not just a visually-near coincidence (see docs/city-model.md's
    # "visual connection implies topological connection" invariant).
    kokzhiek = b.add_road(
        "Kokzhiek Access Road",
        road_type=RoadType.SERVICE,
        points=[(320.0, 250.0), (350.0, 262.0)],
        one_way=True,
        speed_limit_kmh=20.0,
        lanes=[{"index": 0}],
    )

    # --- Zevit Slip Road: one-way slip connector bypassing the main
    # signalized intersection (Zhastar's lane-drop node -> Turan Avenue).
    # Both endpoints exactly match existing nodes/points -- the lane-drop
    # Intersection's position, and an existing vertex already on Turan
    # Avenue (eastbound)'s own polyline -- rather than a near-miss
    # coordinate, so it is a real graph connection at both ends.
    zevit_slip = b.add_road(
        "Zevit Slip Road",
        road_type=RoadType.COLLECTOR,
        points=[(200.0, 220.0), (210.0, 190.0), (220.0, 152.0)],
        one_way=True,
        speed_limit_kmh=30.0,
        lanes=[{"index": 0}],
    )

    # --- Round Park Drive: curved collector loop, both directions --------
    # An intentionally isolated scenic loop (touches nothing else) -- not
    # a defect: it never visually appears connected to another road, so
    # there is no true-topology mismatch to fix here.
    b.add_road(
        "Round Park Drive",
        key="round-park-outbound",
        road_type=RoadType.COLLECTOR,
        points=[(350.0, 40.0), (390.0, 70.0), (400.0, 120.0), (385.0, 170.0)],
        one_way=True,
        speed_limit_kmh=40.0,
        lanes=[{"index": 0}],
    )
    b.add_road(
        "Round Park Drive",
        key="round-park-inbound",
        road_type=RoadType.COLLECTOR,
        points=[(383.0, 172.0), (398.0, 122.0), (388.0, 72.0), (348.0, 42.0)],
        one_way=True,
        speed_limit_kmh=40.0,
        lanes=[{"index": 0}],
    )

    # --- Zharyq Approach / Zharyq Alley: acute/Y junction ------------------
    # A stem road feeding into a shallow (~35 degree) fork alongside Bereke
    # Lane's own start point -- a genuine 3-way acute junction, isolated
    # north of everything else so it can be inspected on its own.
    zharyq_approach = b.add_road(
        "Zharyq Approach",
        road_type=RoadType.RESIDENTIAL,
        points=[(80.0, 10.0), (80.0, 50.0)],
        one_way=True,
        speed_limit_kmh=30.0,
        lanes=[{"index": 0}],
    )
    zharyq_alley = b.add_road(
        "Zharyq Alley",
        road_type=RoadType.RESIDENTIAL,
        points=[(80.0, 50.0), (115.0, 15.0)],
        one_way=True,
        speed_limit_kmh=30.0,
        lanes=[{"index": 0}],
    )

    # --- Yeraly Street: single-lane approach forking into two single-lane
    # branches -- the diverge/split counterpart to Zhastar Street's lane
    # drop above, isolated south of the main district. -----------------
    yeraly_approach = b.add_road(
        "Yeraly Street",
        key="yeraly-approach",
        road_type=RoadType.RESIDENTIAL,
        points=[(260.0, 380.0), (260.0, 340.0)],
        one_way=True,
        speed_limit_kmh=30.0,
        lanes=[{"index": 0}],
    )
    yeraly_branch_west = b.add_road(
        "Yeraly Street West",
        key="yeraly-branch-west",
        road_type=RoadType.RESIDENTIAL,
        points=[(260.0, 340.0), (230.0, 305.0)],
        one_way=True,
        speed_limit_kmh=30.0,
        lanes=[{"index": 0}],
    )
    yeraly_branch_east = b.add_road(
        "Yeraly Street East",
        key="yeraly-branch-east",
        road_type=RoadType.RESIDENTIAL,
        points=[(260.0, 340.0), (290.0, 305.0)],
        one_way=True,
        speed_limit_kmh=30.0,
        lanes=[{"index": 0}],
    )

    # --- Intersections -----------------------------------------------------
    main_intersection_id = _id("intersection", "turan-x-zhastar")
    main_connected_roads = [eastbound, westbound, zhastar_north_near, zhastar_south]
    main_connected_lanes = [
        b.lane_id("turan-eastbound", 0),
        b.lane_id("turan-eastbound", 1),
        b.lane_id("turan-eastbound", 2),
        b.lane_id("turan-westbound", 0),
        b.lane_id("turan-westbound", 1),
        b.lane_id("turan-westbound", 2),
        b.lane_id("zhastar-north-near", 0),
        b.lane_id("zhastar-north-near", 1),
        b.lane_id("zhastar-south", 0),
        b.lane_id("zhastar-south", 1),
    ]
    traffic_light_id = _id("signal", "turan-x-zhastar")
    ns_group_id = _id("signal-group", "turan-x-zhastar", "ns")
    ew_group_id = _id("signal-group", "turan-x-zhastar", "ew")

    samal_intersection_id = _id("intersection", "turan-x-samal")
    bereke_intersection_id = _id("intersection", "turan-x-bereke")
    lane_drop_node_id = _id("intersection", "zhastar-lane-drop")
    kokzhiek_junction_id = _id("intersection", "samal-x-kokzhiek")
    slip_road_junction_id = _id("intersection", "turan-x-zevit-slip")

    intersections = [
        IntersectionCreate(
            id=main_intersection_id,
            position=_pt(200.0, 150.0),
            connected_road_ids=main_connected_roads,
            connected_lane_ids=main_connected_lanes,
            control_type=IntersectionControlType.TRAFFIC_LIGHT,
            traffic_light_id=traffic_light_id,
        ),
        IntersectionCreate(
            id=samal_intersection_id,
            position=_pt(320.0, 150.0),
            connected_road_ids=[eastbound, westbound, samal],
            connected_lane_ids=[b.lane_id("Samal Street", 0)],
            control_type=IntersectionControlType.STOP_SIGN,
        ),
        IntersectionCreate(
            id=bereke_intersection_id,
            position=_pt(80.0, 150.0),
            connected_road_ids=[eastbound, westbound, bereke],
            connected_lane_ids=[b.lane_id("Bereke Lane", 0)],
            control_type=IntersectionControlType.UNCONTROLLED,
        ),
        # Lane-drop node, also where the slip road branches off (a real
        # 3-way junction, not merely a pass-through point).
        IntersectionCreate(
            id=lane_drop_node_id,
            position=_pt(200.0, 220.0),
            connected_road_ids=[zhastar_north_near, zhastar_north_far, zevit_slip],
            control_type=IntersectionControlType.UNCONTROLLED,
        ),
        # T-junction: Kokzhiek Access Road branches off Samal Street.
        IntersectionCreate(
            id=kokzhiek_junction_id,
            position=_pt(320.0, 250.0),
            connected_road_ids=[samal, kokzhiek],
            control_type=IntersectionControlType.UNCONTROLLED,
        ),
        # Skewed merge: the slip road rejoins Turan Avenue at a shallow
        # angle rather than square-on.
        IntersectionCreate(
            id=slip_road_junction_id,
            position=_pt(220.0, 152.0),
            connected_road_ids=[zevit_slip, eastbound],
            control_type=IntersectionControlType.UNCONTROLLED,
        ),
        # Dead-end turn-around: Zhastar Street's far northbound segment
        # ends exactly where its southbound segment begins (200, 300) --
        # a real node (a cul-de-sac turnaround), not a coincidental reuse
        # of the same coordinate for two unrelated things.
        IntersectionCreate(
            id=_id("intersection", "zhastar-north-turnaround"),
            position=_pt(200.0, 300.0),
            connected_road_ids=[zhastar_north_far, zhastar_south],
            control_type=IntersectionControlType.UNCONTROLLED,
        ),
        # Acute/Y junction: a shallow-angle 3-way fork.
        IntersectionCreate(
            id=_id("intersection", "zharyq-fork"),
            position=_pt(80.0, 50.0),
            connected_road_ids=[zharyq_approach, bereke, zharyq_alley],
            control_type=IntersectionControlType.UNCONTROLLED,
        ),
        # Diverge/split: one single-lane approach forking into two
        # single-lane branches.
        IntersectionCreate(
            id=_id("intersection", "yeraly-fork"),
            position=_pt(260.0, 340.0),
            connected_road_ids=[yeraly_approach, yeraly_branch_west, yeraly_branch_east],
            control_type=IntersectionControlType.UNCONTROLLED,
        ),
    ]

    traffic_lights = [
        TrafficLightCreate(
            id=traffic_light_id,
            intersection_id=main_intersection_id,
            signal_groups=[
                SignalGroupCreate(
                    id=ns_group_id,
                    name="North-South",
                    controlled_lane_ids=[
                        b.lane_id("zhastar-north-near", 0),
                        b.lane_id("zhastar-north-near", 1),
                        b.lane_id("zhastar-south", 0),
                        b.lane_id("zhastar-south", 1),
                    ],
                ),
                SignalGroupCreate(
                    id=ew_group_id,
                    name="East-West",
                    controlled_lane_ids=[
                        b.lane_id("turan-eastbound", 0),
                        b.lane_id("turan-eastbound", 1),
                        b.lane_id("turan-eastbound", 2),
                        b.lane_id("turan-westbound", 0),
                        b.lane_id("turan-westbound", 1),
                        b.lane_id("turan-westbound", 2),
                    ],
                ),
            ],
            phases=[
                PhaseCreate(
                    id=_id("phase", "turan-x-zhastar", "ew"),
                    name="East-West green",
                    duration_seconds=35,
                    green_signal_group_ids=[ew_group_id],
                ),
                PhaseCreate(
                    id=_id("phase", "turan-x-zhastar", "ns"),
                    name="North-South green",
                    duration_seconds=25,
                    green_signal_group_ids=[ns_group_id],
                ),
            ],
        )
    ]

    parking_zones = [
        ParkingZoneCreate(
            id=_id("parking", "samal-street"),
            road_id=samal,
            lane_id=b.lane_id("Samal Street", 0),
            allowed=True,
            side=ParkingSide.RIGHT,
            capacity=12,
        ),
    ]

    bus_stops = [
        BusStopCreate(
            id=_id("bus-stop", "turan-eastbound-near-samal"),
            road_id=eastbound,
            position_x=90.0,
            position_y=152.0,
            name="Turan Avenue / Samal Street",
        ),
        BusStopCreate(
            id=_id("bus-stop", "samal-street"),
            road_id=samal,
            position_x=320.0,
            position_y=100.0,
            name="Samal Street",
        ),
    ]

    crosswalks = [
        # Pedestrian crossing on Zhastar Street's southbound approach, just
        # before the signalized main intersection.
        CrosswalkCreate(
            id=_id("crosswalk", "zhastar-south-at-main"),
            road_id=zhastar_south,
            position_ratio=0.95,
        ),
        # Pedestrian crossing at the Samal Street / Turan Avenue stop-sign
        # junction.
        CrosswalkCreate(
            id=_id("crosswalk", "samal-at-turan"),
            road_id=samal,
            position_ratio=0.5,
        ),
    ]

    # Routable demand (source != destination) so Traffic Analysis produces
    # real (not fabricated) congestion coloring on this district -- see
    # docs/city-model.md: a synthetic hardcoded "demo congestion" overlay
    # was deliberately not built when the real analysis pipeline already
    # does this correctly from demand data.
    traffic_demands = [
        TrafficDemandCreate(
            id=_id("demand", "bereke-to-samal"),
            source_intersection_id=bereke_intersection_id,
            destination_intersection_id=samal_intersection_id,
            vehicles_per_hour=1400.0,
            time_interval="AM peak (demo)",
        ),
        TrafficDemandCreate(
            id=_id("demand", "samal-to-zhastar-north"),
            source_intersection_id=samal_intersection_id,
            destination_intersection_id=lane_drop_node_id,
            vehicles_per_hour=900.0,
            time_interval="AM peak (demo)",
        ),
    ]

    return CityCreate(
        id=DEMO_DISTRICT_CITY_ID,
        name=DEMO_DISTRICT_CITY_NAME,
        description=DEMO_DISTRICT_DESCRIPTION,
        coordinate_system=CoordinateSystem.LOCAL_CARTESIAN,
        roads=b.roads,
        intersections=intersections,
        traffic_lights=traffic_lights,
        traffic_rules=[],
        parking_zones=parking_zones,
        traffic_demands=traffic_demands,
        bus_stops=bus_stops,
        crosswalks=crosswalks,
    )
